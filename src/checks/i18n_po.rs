//! Slint & Rust dual-end `.po` translation catalog synchronizer and generator.
//!
//! Reconciles standard gettext `.po` catalogs across locales into a sorted,
//! binary-searchable static Rust array of entries for zero-cost runtime lookup.

use crate::report::{Diagnostic, Severity, normalize_rel_path};
use anyhow::{Context, Result, bail};
use std::collections::{BTreeMap, BTreeSet};
use std::fs;
use std::path::{Path, PathBuf};

/// Parse a `.po` catalog file into a map of `msgid -> msgstr`.
pub fn parse_po(path: &Path) -> Result<BTreeMap<String, String>> {
    let content =
        fs::read_to_string(path).with_context(|| format!("Failed to read {}", path.display()))?;
    let mut entries = BTreeMap::new();
    let mut msgid: Option<String> = None;
    let mut msgstr: Option<String> = None;
    let mut field = Field::None;

    fn flush(
        entries: &mut BTreeMap<String, String>,
        msgid: &mut Option<String>,
        msgstr: &mut Option<String>,
    ) {
        if let (Some(id), Some(value)) = (msgid.take(), msgstr.take())
            && !id.is_empty()
        {
            entries.insert(id, value);
        }
    }

    for line in content.lines() {
        let line = line.trim_end();
        if line.is_empty() || line.starts_with('#') {
            flush(&mut entries, &mut msgid, &mut msgstr);
            field = Field::None;
            continue;
        }
        if let Some(rest) = line.strip_prefix("msgid ") {
            flush(&mut entries, &mut msgid, &mut msgstr);
            msgid = Some(po_string(rest, path)?);
            field = Field::Msgid;
        } else if let Some(rest) = line.strip_prefix("msgstr ") {
            msgstr = Some(po_string(rest, path)?);
            field = Field::Msgstr;
        } else if line.starts_with('"') {
            let text = po_string(line, path)?;
            match field {
                Field::Msgid => {
                    if let Some(id) = msgid.as_mut() {
                        id.push_str(&text);
                    }
                }
                Field::Msgstr => {
                    if let Some(value) = msgstr.as_mut() {
                        value.push_str(&text);
                    }
                }
                Field::None => {}
            }
        }
    }
    flush(&mut entries, &mut msgid, &mut msgstr);
    Ok(entries)
}

#[derive(Clone, Copy)]
enum Field {
    None,
    Msgid,
    Msgstr,
}

fn po_string(raw: &str, path: &Path) -> Result<String> {
    let raw = raw.trim();
    let inner = raw
        .strip_prefix('"')
        .and_then(|raw| raw.strip_suffix('"'))
        .with_context(|| format!("{}: malformed .po string: {raw}", path.display()))?;

    let mut out = String::with_capacity(inner.len());
    let mut chars = inner.chars();
    while let Some(ch) = chars.next() {
        if ch != '\\' {
            out.push(ch);
            continue;
        }
        match chars.next() {
            Some('n') => out.push('\n'),
            Some('t') => out.push('\t'),
            Some('r') => out.push('\r'),
            Some('"') => out.push('"'),
            Some('\\') => out.push('\\'),
            Some(other) => {
                out.push('\\');
                out.push(other);
            }
            None => bail!(
                "{}: trailing backslash in .po string: {raw}",
                path.display()
            ),
        }
    }
    Ok(out)
}

fn rust_string(value: &str) -> String {
    let mut out = String::with_capacity(value.len() + 2);
    out.push('"');
    for ch in value.chars() {
        match ch {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            other => out.push(other),
        }
    }
    out.push('"');
    out
}

pub fn generate_catalog(lang_dir: &Path, domain: &str, locales: &[String]) -> Result<String> {
    if locales.is_empty() {
        bail!("At least one locale must be configured");
    }

    let catalogs: Vec<BTreeMap<String, String>> = locales
        .iter()
        .map(|locale| {
            let path = lang_dir
                .join(locale)
                .join("LC_MESSAGES")
                .join(format!("{domain}.po"));
            parse_po(&path)
        })
        .collect::<Result<_>>()?;

    let mut msgids: BTreeMap<&str, ()> = BTreeMap::new();
    for catalog in &catalogs {
        for msgid in catalog.keys() {
            msgids.insert(msgid.as_str(), ());
        }
    }

    let num_locales = locales.len();
    let mut out = String::new();
    out.push_str(
        r#"//! Auto-generated by cargo-warden i18n — do not edit by hand.
//!
//! Mirrors gettext `.po` catalogs for high-performance binary search lookups.

pub(crate) struct Entry {
    pub(crate) msgid: &'static str,
    pub(crate) translations: [&'static str; "#,
    );
    out.push_str(&format!("{num_locales}],\n}}\n\n"));
    out.push_str("#[rustfmt::skip]\npub(crate) static CATALOG: &[Entry] = &[\n");

    for msgid in msgids.keys() {
        let mut trans = vec![*msgid; num_locales];
        for (idx, catalog) in catalogs.iter().enumerate() {
            if let Some(val) = catalog.get(*msgid).filter(|v| !v.is_empty()) {
                trans[idx] = val.as_str();
            }
        }
        out.push_str("    Entry { msgid: ");
        out.push_str(&rust_string(msgid));
        out.push_str(", translations: [");
        for (i, t) in trans.iter().enumerate() {
            if i > 0 {
                out.push_str(", ");
            }
            out.push_str(&rust_string(t));
        }
        out.push_str("] },\n");
    }
    out.push_str("];\n");
    Ok(out)
}

fn normalize(text: &str) -> String {
    text.replace("\r\n", "\n")
}

/// Options for running i18n catalog sync checks.
#[derive(Debug, Clone)]
pub struct I18nOptions<'a> {
    pub base_dir: &'a Path,
    pub lang_dir: &'a Path,
    pub domain: &'a str,
    pub locales: &'a [String],
    pub out_file: &'a Path,
    pub changeset: Option<&'a BTreeSet<PathBuf>>,
    pub emit_text: bool,
}

fn should_run_i18n_changeset(
    base_dir: &Path,
    lang_dir: &Path,
    out_file: &Path,
    changeset: &BTreeSet<PathBuf>,
) -> bool {
    let lang_rel = normalize_rel_path(base_dir, lang_dir)
        .to_string_lossy()
        .replace('\\', "/");
    let out_rel = normalize_rel_path(base_dir, out_file)
        .to_string_lossy()
        .replace('\\', "/");
    changeset.iter().any(|p| {
        let s = p.to_string_lossy().replace('\\', "/");
        s == out_rel
            || s == "warden.toml"
            || s == ".warden.toml"
            || s.starts_with(&format!("{lang_rel}/"))
    })
}

/// Collect structured i18n synchronization diagnostics.
pub fn collect_i18n(opts: &I18nOptions<'_>) -> Result<Vec<Diagnostic>> {
    if let Some(changed) = opts.changeset
        && !should_run_i18n_changeset(opts.base_dir, opts.lang_dir, opts.out_file, changed)
    {
        tracing::info!("skipping i18n check (no .po or catalog changes)");
        return Ok(Vec::new());
    }

    tracing::debug!(
        lang_dir = %opts.lang_dir.display(),
        domain = opts.domain,
        locales = ?opts.locales,
        out_file = %opts.out_file.display(),
        "checking i18n catalog synchronization"
    );
    if opts.emit_text {
        println!(
            "[i18n] checking catalog sync: {} against {}",
            opts.lang_dir.display(),
            opts.out_file.display()
        );
    }

    let generated = generate_catalog(opts.lang_dir, opts.domain, opts.locales)?;
    let on_disk = fs::read_to_string(opts.out_file)
        .with_context(|| format!("Failed to read target catalog {}", opts.out_file.display()))?;

    let rel_out = normalize_rel_path(opts.base_dir, opts.out_file);
    let rel_str = rel_out.to_string_lossy().replace('\\', "/");

    if normalize(&generated) == normalize(&on_disk) {
        if opts.emit_text {
            println!(
                "[i18n] OK: {} is in sync with .po catalogs",
                opts.out_file.display()
            );
        }
        Ok(Vec::new())
    } else {
        Ok(vec![Diagnostic {
            rule_id: "warden/i18n".to_string(),
            check: "i18n".to_string(),
            severity: Severity::Error,
            message: format!(
                "Translation catalog {} is out of sync with .po catalogs. Run `cargo warden i18n generate` to refresh.",
                rel_out.display()
            ),
            file: Some(rel_out),
            line: None,
            column: None,
            fingerprint: format!("i18n:sync:{rel_str}"),
            metric_value: None,
            suppressed: false,
            suppression_reason: None,
        }])
    }
}

pub fn check_i18n(
    lang_dir: &Path,
    domain: &str,
    locales: &[String],
    out_file: &Path,
) -> Result<()> {
    let diagnostics = collect_i18n(&I18nOptions {
        base_dir: Path::new("."),
        lang_dir,
        domain,
        locales,
        out_file,
        changeset: None,
        emit_text: true,
    })?;
    if let Some(first) = diagnostics.iter().find(|d| !d.suppressed) {
        bail!("{}", first.message);
    }
    Ok(())
}

pub fn sync_i18n(lang_dir: &Path, domain: &str, locales: &[String], out_file: &Path) -> Result<()> {
    let content = generate_catalog(lang_dir, domain, locales)?;
    if let Some(parent) = out_file.parent() {
        fs::create_dir_all(parent)?;
    }
    fs::write(out_file, content)?;
    println!("[i18n] wrote Rust catalog -> {}", out_file.display());
    Ok(())
}
